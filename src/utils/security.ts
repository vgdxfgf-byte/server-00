export async function hashSecurityPassword(password: string, salt: string): Promise<string> {
  const input = `${salt}:${password}`;
  if (typeof window !== 'undefined' && window.crypto?.subtle) {
    const encoded = new TextEncoder().encode(input);
    const digest = await window.crypto.subtle.digest('SHA-256', encoded);
    return Array.from(new Uint8Array(digest))
      .map((b) => b.toString(16).padStart(2, '0'))
      .join('');
  }
  return sha256Fallback(input);
}

function timingSafeEqualHex(a: string, b: string): boolean {
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i++) {
    diff |= a.charCodeAt(i) ^ b.charCodeAt(i);
  }
  return diff === 0;
}

export async function verifySecurityCredentials(
  usernameInput: string,
  passwordInput: string,
  config: AppSecurityConfig
): Promise<boolean> {
  const normalizedUser = usernameInput.trim().toLowerCase();
  const expectedUser = config.username.trim().toLowerCase();
  if (!normalizedUser || normalizedUser !== expectedUser) {
    return false;
  }
  if (!passwordInput) {
    return false;
  }
  const computed = await hashSecurityPassword(passwordInput, config.passwordSalt);
  return timingSafeEqualHex(computed, config.passwordHash.toLowerCase());
}
